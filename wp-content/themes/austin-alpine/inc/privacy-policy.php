function alpine_ensure_privacy_policy_page() {
    if (get_option('alpine_privacy_policy_content_version') === ALPINE_PRIVACY_POLICY_VERSION) {
        return;
    }

    $page = get_page_by_path('privacy-policy', OBJECT, 'page');

    if (!$page) {
        $registered_id = (int) get_option('wp_page_for_privacy_policy');

        if ($registered_id && 'page' === get_post_type($registered_id) && 'trash' !== get_post_status($registered_id)) {
            $page = get_post($registered_id);
        }
    }

    $postarr = array(
        'post_title'   => 'Privacy Policy',
        'post_content' => alpine_get_privacy_policy_content(),
        'post_status'  => 'publish',
        'post_type'    => 'page',
        'post_name'    => 'privacy-policy',
    );

    // Saved as a trusted theme write, not filtered through the visitor's kses rules.
    kses_remove_filters();

    if ($page) {
        $postarr['ID'] = $page->ID;
        $page_id = wp_update_post(wp_slash($postarr), true);
    } else {
        $page_id = wp_insert_post(wp_slash($postarr), true);
    }

    kses_init();

    if (is_wp_error($page_id) || !$page_id) {
        return;
    }

    update_option('wp_page_for_privacy_policy', (int) $page_id);
    update_option('alpine_privacy_policy_content_version', ALPINE_PRIVACY_POLICY_VERSION);
}
add_action('init', 'alpine_ensure_privacy_policy_page', 32);
